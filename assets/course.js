const STORE = "py-java-course-complete";
const getDone = () => new Set(JSON.parse(localStorage.getItem(STORE) || "[]"));
const setDone = (set) => localStorage.setItem(STORE, JSON.stringify([...set]));

function currentModule() {
  const path = location.pathname.replaceAll("\\", "/");
  return COURSE_DATA.find(m => path.endsWith(m.file) || path.endsWith(m.file.replace("modules/", "")));
}

function renderSidebar() {
  const holder = document.querySelector("[data-sidebar-list]");
  if (!holder) return;
  const cur = currentModule();
    holder.innerHTML = COURSE_DATA.map(m => {
    const active = cur && cur.id === m.id ? "active" : "";
    const href = document.body.dataset.root + m.file;
    const lessons = active ? `<div class="ml-3 mt-1">${m.lessons.map((l, i) => `<a class="navlink text-sm" href="#lesson-${i+1}">${l}</a>`).join("")}</div>` : "";
    const search = `${m.title} ${m.lessons.join(" ")}`.toLowerCase();
    return `<a class="navlink ${active}" data-title="${search}" href="${href}">M${m.number}. ${m.title}</a>${lessons}`;
  }).join("");
}

function renderToc() {
  const toc = document.querySelector("[data-toc]");
  if (!toc) return;
  const heads = [...document.querySelectorAll(".lesson h2")];
  toc.innerHTML = heads.map(h => `<a class="navlink text-sm" href="#${h.parentElement.id}">${h.textContent}</a>`).join("");
}

function enhanceCode() {
  document.querySelectorAll(".codebox").forEach(box => {
    if (box.querySelector(".copy")) return;
    const btn = document.createElement("button");
    btn.className = "copy";
    btn.type = "button";
    btn.textContent = "Copy";
    btn.addEventListener("click", async () => {
      const code = box.querySelector("code")?.innerText || "";
      await navigator.clipboard.writeText(code);
      btn.textContent = "Copied";
      setTimeout(() => btn.textContent = "Copy", 900);
    });
    box.appendChild(btn);
  });
}

function updateProgress() {
  const done = getDone();
  const total = COURSE_DATA.reduce((sum, m) => sum + m.lessons.length, 0);
  const count = [...done].length;
  document.querySelectorAll("[data-progress-bar]").forEach(el => el.style.width = `${total ? count / total * 100 : 0}%`);
  document.querySelectorAll("[data-progress-text]").forEach(el => el.textContent = `${count}/${total} lessons complete`);
}

function wireComplete() {
  const done = getDone();
  document.querySelectorAll("[data-lesson-id]").forEach(section => {
    const id = section.dataset.lessonId;
    const btn = section.querySelector("[data-complete]");
    if (!btn) return;
    const paint = () => {
      btn.classList.toggle("done", done.has(id));
      btn.textContent = done.has(id) ? "Complete" : "Mark complete";
    };
    btn.addEventListener("click", () => {
      done.has(id) ? done.delete(id) : done.add(id);
      setDone(done);
      paint();
      updateProgress();
    });
    paint();
  });
}

function wireSearch() {
  const input = document.querySelector("[data-search]");
  if (!input) return;
  input.addEventListener("input", () => {
    const q = input.value.trim().toLowerCase();
    document.querySelectorAll("[data-title]").forEach(a => {
      a.style.display = a.dataset.title.includes(q) ? "" : "none";
    });
    document.querySelectorAll("[data-module-card]").forEach(card => {
      card.style.display = card.dataset.search.includes(q) ? "" : "block";
    });
  });
}

function wireTheme() {
  const key = "py-java-theme";
  const apply = () => document.documentElement.classList.toggle("light", localStorage.getItem(key) === "light");
  document.querySelectorAll("[data-theme]").forEach(btn => btn.addEventListener("click", () => {
    localStorage.setItem(key, localStorage.getItem(key) === "light" ? "dark" : "light");
    apply();
  }));
  apply();
}

function wireDrawer() {
  const btn = document.querySelector("[data-drawer]");
  const sidebar = document.querySelector(".sidebar");
  const dim = document.querySelector(".mobile-dim");
  if (!btn || !sidebar || !dim) return;
  const toggle = () => { sidebar.classList.toggle("open"); dim.classList.toggle("show"); };
  btn.addEventListener("click", toggle);
  dim.addEventListener("click", toggle);
}

function wireKeys() {
  document.addEventListener("keydown", e => {
    if (e.altKey || e.ctrlKey || e.metaKey || e.target.matches("input, textarea")) return;
    const next = e.key === "ArrowRight" && document.querySelector("[data-next]");
    const prev = e.key === "ArrowLeft" && document.querySelector("[data-prev]");
    const link = next || prev;
    if (link) location.href = link.href;
  });
}

document.addEventListener("DOMContentLoaded", () => {
  renderSidebar(); renderToc(); enhanceCode(); wireComplete(); wireSearch(); wireTheme(); wireDrawer(); wireKeys(); updateProgress();
});
